/**
 * `npm run typecheck` is three programs (Nov 16 2026): the app
 * (tsconfig.build.json), the unit tests (tsconfig.tests.json) and the browser
 * specs (tsconfig.e2e.json). As one program the repository needed 4.21 GB
 * against the 4 GB heap. The price of a split is that a file can fall between
 * the programs and never be checked — this pins that none does.
 */
import { describe, it, expect } from 'vitest';
import ts from 'typescript';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(__dirname, '../../..');
const CONFIGS = ['tsconfig.build.json', 'tsconfig.tests.json', 'tsconfig.e2e.json'];
const SOURCE_RE = /\.(ts|tsx|mts)$/;
const SKIP_DIRS = new Set(['node_modules', '.next', '.git', 'test-results', 'playwright-report']);

function filesOf(config: string): string[] {
  const file = path.join(ROOT, config);
  const read = ts.readConfigFile(file, ts.sys.readFile);
  if (read.error) throw new Error(`${config}: cannot be read`);
  return ts.parseJsonConfigFileContent(read.config, ts.sys, ROOT, undefined, file).fileNames.map((f) => path.resolve(f));
}

function walk(dir: string, out: string[]): string[] {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) walk(path.join(dir, entry.name), out);
    } else if (SOURCE_RE.test(entry.name)) {
      out.push(path.join(dir, entry.name));
    }
  }
  return out;
}

/** Every TypeScript file the repository owns: src, e2e, scripts and the root's config files. */
function ownedFiles(): string[] {
  const out: string[] = [];
  for (const dir of ['src', 'e2e', 'scripts']) {
    const full = path.join(ROOT, dir);
    if (fs.existsSync(full)) walk(full, out);
  }
  for (const entry of fs.readdirSync(ROOT, { withFileTypes: true })) {
    // next-env.d.ts is generated by the build and gitignored.
    if (entry.isFile() && SOURCE_RE.test(entry.name) && entry.name !== 'next-env.d.ts') out.push(path.join(ROOT, entry.name));
  }
  return out;
}

describe('the type check covers every file', () => {
  const byConfig = new Map(CONFIGS.map((c) => [c, new Set(filesOf(c))]));

  it('no TypeScript file falls between the three programs', () => {
    const missed = ownedFiles()
      .filter((f) => !CONFIGS.some((c) => byConfig.get(c)!.has(f)))
      .map((f) => path.relative(ROOT, f));
    expect(missed).toEqual([]);
  });

  it('the app program holds no test and no browser spec (that is what keeps it under the heap)', () => {
    const strays = [...byConfig.get('tsconfig.build.json')!]
      .map((f) => path.relative(ROOT, f))
      .filter((f) => f.startsWith('e2e/') || /\.test\.tsx?$/.test(f) || f.includes('/__tests__/'));
    expect(strays).toEqual([]);
  });

  it('the typecheck script runs all three programs and each keeps its own incremental cache', () => {
    const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8')) as { scripts: Record<string, string> };
    for (const name of ['typecheck:app', 'typecheck:tests', 'typecheck:e2e']) {
      expect(pkg.scripts.typecheck).toContain(`npm run ${name}`);
    }
    const run = `${pkg.scripts['typecheck:app']} ${pkg.scripts['typecheck:tests']} ${pkg.scripts['typecheck:e2e']}`;
    for (const config of CONFIGS) expect(run).toContain(`-p ${config}`);
    const caches = CONFIGS.map((c) => {
      const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, c), 'utf8')) as { compilerOptions?: { tsBuildInfoFile?: string } };
      return cfg.compilerOptions?.tsBuildInfoFile;
    });
    expect(caches.every(Boolean)).toBe(true);
    expect(new Set(caches).size).toBe(CONFIGS.length);
  });
});
