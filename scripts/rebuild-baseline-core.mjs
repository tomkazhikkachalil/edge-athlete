/**
 * The rebuild baseline, pure: `schema_dump()`'s jsonb (migration 227) →
 * the text of `database/baseline/000_rebuild.sql` (Round 2 — a rebuildable
 * chain, Sep 2026). No I/O here; `build-rebuild-baseline.mjs` is the CLI.
 *
 * Emission order is dependency order on a BLANK database: extensions →
 * enum types → sequences → functions pass 1 (defaults, CHECKs and
 * expression indexes call them; row-type signatures fail silently here) →
 * tables (columns only) → PK / UNIQUE / CHECK /
 * EXCLUDE → FKs (after every table) → indexes a constraint does not own →
 * views → functions (check_function_bodies off: a SQL-language body may
 * name a later function) → triggers → RLS + policies → grants → comments →
 * storage buckets → the realtime publication → the reference rows → the
 * ledger seed (every chain file up to the dump's head, 'rebuild-000') →
 * pg_cron jobs (COMMENTED OUT — they carry the SOURCE project's URL and a
 * redacted token; re-created by hand after the app's URL is known).
 *
 * Everything is guarded (IF NOT EXISTS / DROP IF EXISTS first / DO blocks)
 * so the file is re-runnable, the house style for every migration.
 */

const q = s => `'${String(s).replace(/'/g, "''")}'`;
// quote_ident's rule: bare when it is a plain lower-case identifier that is
// not a reserved word; double-quoted otherwise.
const RESERVED = new Set(('all analyse analyze and any array as asc asymmetric authorization binary both case cast check collate collation column concurrently constraint create cross current_catalog current_date current_role current_schema current_time current_timestamp current_user default deferrable desc distinct do else end except false fetch for foreign freeze from full grant group having ilike in initially inner intersect into is isnull join lateral leading left like limit localtime localtimestamp natural not notnull null offset on only or order outer overlaps placing primary references returning right select session_user similar some symmetric system_user table tablesample then to trailing true union unique user using variadic verbose when where window with').split(' '));
const ident = s => (/^[a-z_][a-z0-9_]*$/.test(s) && !RESERVED.has(s) ? s : `"${s.replace(/"/g, '""')}"`);
const qt = (schema, table) => `${ident(schema)}.${ident(table)}`;
const API_ROLES = ['anon', 'authenticated', 'service_role'];

function section(title) {
  return `\n-- ── ${title} ${'─'.repeat(Math.max(3, 74 - title.length))}\n`;
}

export function emitExtensions(exts) {
  return exts.map(e => `CREATE EXTENSION IF NOT EXISTS ${ident(e.name)}${e.schema && e.schema !== 'pg_catalog' ? ` WITH SCHEMA ${ident(e.schema)}` : ''};`).join('\n');
}

export function emitTypes(types) {
  return types.map(t => `DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type x JOIN pg_namespace n ON n.oid = x.typnamespace WHERE n.nspname = 'public' AND x.typname = ${q(t.name)}) THEN
    CREATE TYPE public.${ident(t.name)} AS ENUM (${(t.labels ?? []).map(q).join(', ')});
  END IF;
END $$;`).join('\n');
}

export function emitSequences(seqs) {
  // Identity sequences are created by their column; only the others are ours.
  return seqs.filter(s => !s.identity).map(s =>
    `CREATE SEQUENCE IF NOT EXISTS public.${ident(s.name)} AS ${s.data_type} START WITH ${s.start} INCREMENT BY ${s.increment} MINVALUE ${s.min} ${BigInt(Math.round(Number(s.max))) < BIGINT_MAX - 1000n ? `MAXVALUE ${s.max}` : 'NO MAXVALUE'}${s.cycle ? ' CYCLE' : ''};`
  ).join('\n');
}

export function emitSequenceOwners(seqs) {
  return seqs.filter(s => !s.identity && s.owned_by).map(s => {
    const [table, col] = s.owned_by.split('.');
    return `ALTER SEQUENCE public.${ident(s.name)} OWNED BY public.${ident(table)}.${ident(col)};`;
  }).join('\n');
}

const BIGINT_MAX = 9223372036854775807n;
/** `(START WITH n …)` for an identity column, from its sequence; '' when every option is the default. */
export function identityOptions(seq) {
  if (!seq) return '';
  const opts = [];
  if (seq.start != null && Number(seq.start) !== 1) opts.push(`START WITH ${seq.start}`);
  if (seq.increment != null && Number(seq.increment) !== 1) opts.push(`INCREMENT BY ${seq.increment}`);
  if (seq.min != null && Number(seq.min) !== 1) opts.push(`MINVALUE ${seq.min}`);
  if (seq.max != null && BigInt(Math.round(Number(seq.max))) < BIGINT_MAX - 1000n) opts.push(`MAXVALUE ${seq.max}`);
  if (seq.cycle) opts.push('CYCLE');
  return opts.length ? ` (${opts.join(' ')})` : '';
}

function columnDef(c, seq) {
  const parts = [ident(c.name), c.type];
  if (c.generated === 's') parts.push(`GENERATED ALWAYS AS (${c.default}) STORED`);
  else if (c.identity === 'a') parts.push(`GENERATED ALWAYS AS IDENTITY${identityOptions(seq)}`);
  else if (c.identity === 'd') parts.push(`GENERATED BY DEFAULT AS IDENTITY${identityOptions(seq)}`);
  else if (c.default != null && c.default !== '') parts.push(`DEFAULT ${c.default}`);
  if (c.not_null) parts.push('NOT NULL');
  return parts.join(' ');
}

export function emitTables(tables, seqs = []) {
  const seqFor = (table, col) => seqs.find(s => s.identity && s.owned_by === `${table}.${col}`);
  return tables.map(t => `CREATE TABLE IF NOT EXISTS public.${ident(t.name)} (\n${(t.columns ?? []).map(c => `  ${columnDef(c, seqFor(t.name, c.name))}`).join(',\n')}\n);`).join('\n\n');
}

/**
 * The same identity options as an idempotent ALTER, for an environment
 * whose table already existed when the rebuild ran (CREATE TABLE IF NOT
 * EXISTS skipped it — the first staging run left tickets.number starting
 * at 1, not 1000). SET START never moves a live counter; a fresh column
 * takes its start from the CREATE.
 */
export function emitIdentityStarts(tables, seqs = []) {
  const out = [];
  for (const s of seqs.filter(x => x.identity && x.owned_by)) {
    const [table, col] = s.owned_by.split('.');
    if (!tables.some(t => t.name === table && (t.columns ?? []).some(c => c.name === col && c.identity))) continue;
    if (s.start != null && Number(s.start) !== 1) out.push(`ALTER TABLE public.${ident(table)} ALTER COLUMN ${ident(col)} SET START WITH ${s.start};`);
  }
  return out.join('\n');
}

const CONSTRAINT_ORDER = { p: 0, u: 1, c: 2, x: 3, f: 4 };
export function emitConstraints(constraints, { foreign }) {
  return constraints
    .filter(k => k.type in CONSTRAINT_ORDER && (k.type === 'f') === foreign)
    .sort((a, b) => (CONSTRAINT_ORDER[a.type] ?? 9) - (CONSTRAINT_ORDER[b.type] ?? 9) || a.table.localeCompare(b.table) || a.name.localeCompare(b.name))
    .map(k => `DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = ${q(k.name)} AND conrelid = 'public.${ident(k.table)}'::regclass) THEN
    ALTER TABLE public.${ident(k.table)} ADD CONSTRAINT ${ident(k.name)} ${k.definition};
  END IF;
END $$;`).join('\n');
}

export function emitIndexes(indexes) {
  return indexes.filter(i => !i.constraint).map(i => {
    const def = i.definition.replace(/^CREATE (UNIQUE )?INDEX /i, (m, u) => `CREATE ${u ?? ''}INDEX IF NOT EXISTS `);
    return `${def};`;
  }).join('\n');
}

export function emitViews(views) {
  return views.map(v => {
    const create = v.materialized
      ? `CREATE MATERIALIZED VIEW IF NOT EXISTS public.${ident(v.name)} AS\n${v.definition.trim().replace(/;$/, '')};`
      : `CREATE OR REPLACE VIEW public.${ident(v.name)} AS\n${v.definition.trim().replace(/;$/, '')};`;
    // 234: a view's reloptions (`security_invoker=true`, `check_option=…`) —
    // pg_get_viewdef never carries them, and a view rebuilt without them is a
    // different view. An idempotent ALTER after the CREATE OR REPLACE.
    const options = (v.options ?? []).filter(o => typeof o === 'string' && o.includes('='));
    if (options.length === 0) return create;
    return `${create}\nALTER ${v.materialized ? 'MATERIALIZED VIEW' : 'VIEW'} public.${ident(v.name)} SET (${options.map(o => o.replace('=', ' = ')).join(', ')});`;
  }).join('\n\n');
}

export function emitFunctions(functions) {
  return functions.map(f => `${f.definition.trim().replace(/;$/, '')};`).join('\n\n');
}

/**
 * Pass 1, BEFORE the tables: a column default, a CHECK or an expression
 * index may call a function (`search_normalize(ascii_name)` — the first
 * staging run stopped there), so every function is attempted early. One
 * whose signature names a row type that does not exist yet fails here and
 * is created by the full pass after the views; the failure is swallowed.
 */
export function emitFunctionsPass1(functions) {
  return functions.map(f => `DO $pass1$ BEGIN
${f.definition.trim().replace(/;$/, '')};
EXCEPTION WHEN OTHERS THEN NULL; -- created by pass 2
END $pass1$;`).join('\n');
}

/**
 * EXECUTE grantees from a proacl (`{=X/postgres,anon=X/postgres}`): '' is
 * PUBLIC; the owner is not a grant. `null` = the default privileges, which
 * on Supabase means PUBLIC — nothing to emit, the new project's defaults
 * say the same. (The first staging run stripped PUBLIC from 24 functions
 * because the dump only knew the three API roles' answers.)
 */
export function aclGrantees(acl, owner = 'postgres') {
  if (acl == null) return null;
  const out = new Set();
  for (const item of acl) {
    const grantee = String(item).split('=')[0];
    if (grantee === owner) continue;
    out.add(grantee === '' ? 'PUBLIC' : grantee.toLowerCase());
  }
  return [...out].sort();
}

export function emitFunctionGrants(functions) {
  return functions.map(f => {
    const sig = `public.${ident(f.name)}(${f.identity_args ?? ''})`;
    const kind = f.kind === 'p' ? 'PROCEDURE' : 'FUNCTION';
    if ('acl' in f) {
      const grantees = aclGrantees(f.acl, f.owner ?? 'postgres');
      if (grantees === null) return `-- ${sig}: default privileges (PUBLIC)`;
      return `REVOKE EXECUTE ON ${kind} ${sig} FROM PUBLIC, anon, authenticated, service_role;${grantees.length ? `\nGRANT EXECUTE ON ${kind} ${sig} TO ${grantees.map(g => (g === 'PUBLIC' ? 'PUBLIC' : ident(g))).join(', ')};` : ''}`;
    }
    // No acl in the dump (pre-catalog merge): the three roles' answers only.
    const to = API_ROLES.filter(r => f.grants?.[r]);
    return `REVOKE EXECUTE ON ${kind} ${sig} FROM PUBLIC, anon, authenticated, service_role;${to.length ? `\nGRANT EXECUTE ON ${kind} ${sig} TO ${to.join(', ')};` : ''}`;
  }).join('\n');
}

export function emitTriggers(triggers) {
  return triggers.map(t => {
    const lines = [`DROP TRIGGER IF EXISTS ${ident(t.name)} ON ${qt(t.schema ?? 'public', t.table)};`, `${t.definition.trim().replace(/;$/, '')};`];
    if (t.enabled === 'D') lines.push(`ALTER TABLE ${qt(t.schema ?? 'public', t.table)} DISABLE TRIGGER ${ident(t.name)};`);
    else if (t.enabled === 'A') lines.push(`ALTER TABLE ${qt(t.schema ?? 'public', t.table)} ENABLE ALWAYS TRIGGER ${ident(t.name)};`);
    else if (t.enabled === 'R') lines.push(`ALTER TABLE ${qt(t.schema ?? 'public', t.table)} ENABLE REPLICA TRIGGER ${ident(t.name)};`);
    return lines.join('\n');
  }).join('\n');
}

export function emitRls(tables) {
  return tables.map(t => {
    const out = [`ALTER TABLE public.${ident(t.name)} ${t.rls ? 'ENABLE' : 'DISABLE'} ROW LEVEL SECURITY;`];
    if (t.rls_forced) out.push(`ALTER TABLE public.${ident(t.name)} FORCE ROW LEVEL SECURITY;`);
    return out.join('\n');
  }).join('\n');
}

export function emitPolicies(policies) {
  return policies.map(p => {
    const on = qt(p.schema ?? 'public', p.table);
    const roles = (p.roles ?? ['public']).map(r => (r === 'public' ? 'public' : ident(r))).join(', ');
    const parts = [`CREATE POLICY ${ident(p.name)} ON ${on}`, `AS ${p.permissive === 'RESTRICTIVE' ? 'RESTRICTIVE' : 'PERMISSIVE'}`, `FOR ${p.cmd ?? 'ALL'}`, `TO ${roles}`];
    if (p.qual) parts.push(`USING (${p.qual})`);
    if (p.with_check) parts.push(`WITH CHECK (${p.with_check})`);
    return `DROP POLICY IF EXISTS ${ident(p.name)} ON ${on};\n${parts.join('\n  ')};`;
  }).join('\n');
}

/** Tables AND views: GRANT ... ON TABLE covers both. */
export function emitTableGrants(tables) {
  return tables.map(t => {
    const out = [`REVOKE ALL ON TABLE public.${ident(t.name)} FROM ${API_ROLES.join(', ')};`];
    for (const role of API_ROLES) {
      const privs = t.grants?.[role];
      if (privs?.length) out.push(`GRANT ${privs.join(', ')} ON TABLE public.${ident(t.name)} TO ${role};`);
    }
    return out.join('\n');
  }).join('\n');
}

export function emitSequenceGrants(seqs) {
  return seqs.map(s => {
    const to = API_ROLES.filter(r => s.grants?.[r]);
    return `REVOKE ALL ON SEQUENCE public.${ident(s.name)} FROM ${API_ROLES.join(', ')};${to.length ? `\nGRANT USAGE ON SEQUENCE public.${ident(s.name)} TO ${to.join(', ')};` : ''}`;
  }).join('\n');
}

export function emitComments(tables, functions) {
  const out = [];
  for (const t of tables) {
    if (t.comment) out.push(`COMMENT ON TABLE public.${ident(t.name)} IS ${q(t.comment)};`);
    for (const c of t.columns ?? []) if (c.comment) out.push(`COMMENT ON COLUMN public.${ident(t.name)}.${ident(c.name)} IS ${q(c.comment)};`);
  }
  for (const f of functions) if (f.comment) out.push(`COMMENT ON ${f.kind === 'p' ? 'PROCEDURE' : 'FUNCTION'} public.${ident(f.name)}(${f.identity_args ?? ''}) IS ${q(f.comment)};`);
  return out.join('\n');
}

export function emitBuckets(buckets) {
  if (!buckets) return '-- (storage.buckets was not readable when the dump ran — create the buckets by hand: see docs/MEDIA_PRIVACY_FLIP.md)';
  return buckets.map(b => `INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (${q(b.id)}, ${q(b.name)}, ${b.public ? 'true' : 'false'}, ${b.file_size_limit ?? 'NULL'}, ${b.allowed_mime_types ? `ARRAY[${b.allowed_mime_types.map(q).join(', ')}]::text[]` : 'NULL'})
ON CONFLICT (id) DO UPDATE SET public = EXCLUDED.public, file_size_limit = EXCLUDED.file_size_limit, allowed_mime_types = EXCLUDED.allowed_mime_types;`).join('\n');
}

export function emitPublications(pubs) {
  return pubs.map(p => `DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = ${q(p.publication)})
     AND NOT EXISTS (SELECT 1 FROM pg_publication_tables WHERE pubname = ${q(p.publication)} AND schemaname = 'public' AND tablename = ${q(p.table)}) THEN
    ALTER PUBLICATION ${ident(p.publication)} ADD TABLE public.${ident(p.table)};
  END IF;
END $$;`).join('\n');
}

export function emitSeedRows(seed) {
  if (!seed) return '-- (no reference rows in the dump)';
  const out = [];
  for (const [table, rows] of Object.entries(seed)) {
    if (!rows?.length) continue;
    const cols = Object.keys(rows[0]);
    const values = rows.map(r => `  (${cols.map(c => (r[c] === null || r[c] === undefined ? 'NULL' : typeof r[c] === 'object' ? `${q(JSON.stringify(r[c]))}::jsonb` : typeof r[c] === 'boolean' ? String(r[c]) : typeof r[c] === 'number' ? String(r[c]) : q(r[c]))).join(', ')})`);
    out.push(`INSERT INTO public.${ident(table)} (${cols.map(ident).join(', ')}) VALUES\n${values.join(',\n')}\nON CONFLICT DO NOTHING;`);
  }
  return out.join('\n\n');
}

export function emitLedgerSeed(chainFiles, head) {
  const rows = chainFiles
    .map(name => ({ number: Number(/^(\d{3})_/.exec(name)?.[1]), name }))
    .filter(r => Number.isInteger(r.number) && (head == null || r.number <= head))
    .map(r => `  (${r.number}, ${q(r.name)}, 'rebuild-000')`);
  if (!rows.length) return '-- (no chain files)';
  return `INSERT INTO public.schema_migrations (number, name, applied_by) VALUES\n${rows.join(',\n')}\nON CONFLICT (number) DO NOTHING;`;
}

export function emitCronJobs(jobs, sourceHost) {
  if (!jobs) return '-- (cron.job was not readable when the dump ran — see 059 and 135 for the two jobs)';
  if (!jobs.length) return '-- (no pg_cron jobs)';
  const lines = ['-- REVIEW BEFORE UNCOMMENTING: each command carried the SOURCE project\'s app URL', '-- (replaced with __APP_URL__ below) and a bearer token (redacted in the database).', '-- Put the NEW environment\'s URL and CRON_SECRET in, then run these by hand.'];
  for (const j of jobs) {
    const cmd = sourceHost ? j.command.split(sourceHost).join('__APP_URL__') : j.command;
    lines.push(`-- SELECT cron.schedule(${q(j.name)}, ${q(j.schedule)}, $cron$${cmd}$cron$);${j.active === false ? ' -- (inactive at the source)' : ''}`);
  }
  return lines.join('\n');
}

/** The whole file. `opts.chainFiles`: the numbered file names on disk; `opts.sourceHost`: the source app host to scrub from cron commands. */
export function buildRebuildSql(dump, opts = {}) {
  const meta = dump.meta ?? {};
  const head = meta.ledger?.head ?? null;
  const tables = dump.tables ?? [];
  const functions = dump.functions ?? [];
  const seqs = dump.sequences ?? [];
  const parts = [];
  parts.push(`-- ============================================================================
-- 000_rebuild — a blank Supabase project → this schema (GENERATED, do not edit)
-- ============================================================================
-- Generated ${meta.generated_at ?? '(unknown)'} from server ${meta.server_version ?? '?'} by
-- \`npm run build:baseline\` (scripts/build-rebuild-baseline.mjs) over
-- public.schema_dump() (migration 227). Ledger head at generation: ${head ?? '(no ledger)'}.
--
-- WHY THIS FILE: the numbered chain does not replay on a blank database
-- (database/MIGRATIONS.md, "To build an environment"). This is the live
-- schema as DDL, in dependency order, every statement guarded so it is
-- re-runnable. Run it WHOLE in the new project's SQL editor; then point
-- .env.local at the project and \`npm run check:schema\` must report 0
-- drift and \`Ledger OK\` — that is the only proof the environment is built.
--
-- NOT in this file, by design: user data; the golf catalog (28k courses —
-- data, copied separately); storage OBJECTS; auth users; secrets. The
-- pg_cron jobs are at the end, commented, for review.
-- ============================================================================

SET check_function_bodies = off;
`);
  parts.push(section('Extensions') + emitExtensions(dump.extensions ?? []));
  parts.push(section('Enum types') + emitTypes(dump.types ?? []));
  parts.push(section('Sequences') + emitSequences(seqs));
  parts.push(section(`Functions, pass 1 (${functions.length}; failures silenced, pass 2 is authoritative)`) + emitFunctionsPass1(functions));
  parts.push(section(`Tables (${tables.length})`) + emitTables(tables, seqs));
  parts.push(section('Sequence owners') + emitSequenceOwners(seqs));
  parts.push(section('Identity starts (for a table that already existed)') + emitIdentityStarts(tables, seqs));
  parts.push(section('Primary keys, unique, check, exclusion') + emitConstraints(dump.constraints ?? [], { foreign: false }));
  parts.push(section('Foreign keys') + emitConstraints(dump.constraints ?? [], { foreign: true }));
  parts.push(section('Indexes') + emitIndexes(dump.indexes ?? []));
  parts.push(section('Views') + emitViews(dump.views ?? []));
  parts.push(section(`Functions, pass 2 (${functions.length})`) + emitFunctions(functions));
  parts.push(section('Triggers') + emitTriggers(dump.triggers ?? []));
  parts.push(section('Row level security') + emitRls(tables));
  parts.push(section(`Policies (${(dump.policies ?? []).length})`) + emitPolicies(dump.policies ?? []));
  parts.push(section('Table and view grants') + emitTableGrants([...tables, ...(dump.views ?? [])]));
  parts.push(section('Sequence grants') + emitSequenceGrants(seqs));
  parts.push(section('Function grants') + emitFunctionGrants(functions));
  parts.push(section('Comments') + emitComments(tables, functions));
  parts.push(section('Storage buckets') + emitBuckets(dump.storage_buckets));
  parts.push(section('Realtime publication') + emitPublications(dump.publications ?? []));
  parts.push(section('Reference rows') + emitSeedRows(dump.seed_rows));
  const hasLedger = tables.some(t => t.name === 'schema_migrations');
  parts.push(section('The ledger: every chain file this rebuild embodies') + (hasLedger ? emitLedgerSeed(opts.chainFiles ?? [], head) : '-- (the source had no schema_migrations table — run 226 there and regenerate)'));
  parts.push(section('pg_cron jobs (review, then run by hand)') + emitCronJobs(dump.cron_jobs, opts.sourceHost));
  const publicPolicies = (dump.policies ?? []).filter(p => (p.schema ?? 'public') === 'public').length;
  parts.push(`
NOTIFY pgrst, 'reload schema';

-- ── Result (ONE row) ─────────────────────────────────────────────────────────
-- Expected: 000 REBUILT | ${tables.length} | ${functions.length} | ${publicPolicies} | ${head ?? 'null'}
SELECT '000 REBUILT' AS result,
       (SELECT count(*) FROM pg_tables WHERE schemaname = 'public') AS tables_expect_${tables.length},
       (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace WHERE n.nspname = 'public' AND p.prokind IN ('f', 'p')
          AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e')
          AND p.proname <> 'rls_auto_enable') AS functions_expect_${functions.length},
       (SELECT count(*) FROM pg_policies WHERE schemaname = 'public') AS policies_expect_${publicPolicies},
       (SELECT max(number) FROM public.schema_migrations) AS ledger_head_expect_${head ?? 'null'};
`);
  return parts.join('\n') + '\n';
}
