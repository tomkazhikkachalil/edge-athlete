-- ============================================================================
-- 226: Round 2 (a second environment + a rebuildable chain) — the migration
--      LEDGER: which numbered files have run here, written by the file itself
-- ============================================================================
-- Until now the only proof a migration ran was `npm run check:schema`'s
-- reverse question (CHAIN-ONLY lines) — and that sees tables, columns,
-- policies, functions, triggers and grants. It cannot see an index, a CHECK
-- constraint, a column default, a backfill UPDATE or a seed row, so a
-- migration made only of those could be skipped and nothing would say so;
-- and a second environment (staging, Round 2) has no way to say "I am at
-- 224" at all. The ledger is the answer, in the simplest shape that works:
--
--   * `schema_migrations(number PRIMARY KEY, name, applied_at, applied_by)`.
--   * FROM 227 ON, EVERY migration ends by inserting its own row (the
--     footer below the result row — a unit test pins it, so a file without
--     the footer never merges). The SQL editor stays the runner: the file
--     records itself, nobody types a number.
--   * `npm run check:schema` reads the ledger's head and fails when it is
--     not the chain's head, naming the files that have not run.
--   * `npm run migrate:mark <n>` is the correction path (a file that ran
--     before its footer existed, or a row deleted by hand).
--
-- The seed: every file on disk today (001–225) is recorded as applied at
-- THIS migration's time by 'backfill-226' — the true dates were never
-- recorded (DEVLOG.md has the days). Service-role only: RLS on, no
-- policies, nothing granted to the API roles. Re-runnable.
--
-- Found while seeding: the chain has NO 217 — the number was skipped
-- between 216 (event media) and 218 (contest stages) and nothing records
-- why. It is the chain's one gap; the ledger test (`migration-ledger.test.ts`)
-- names it, so the next skipped number is a failing test, not a mystery.
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.schema_migrations (
  number      integer PRIMARY KEY,
  name        text NOT NULL,
  applied_at  timestamptz NOT NULL DEFAULT now(),
  applied_by  text NOT NULL DEFAULT 'sql-editor'
);
COMMENT ON TABLE public.schema_migrations IS '226: which numbered migration files have run in THIS database. Each file inserts its own row (from 227 on); check:schema compares the head to the chain.';

ALTER TABLE public.schema_migrations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.schema_migrations FROM anon, authenticated;

